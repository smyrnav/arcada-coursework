#!/usr/bin/env python3
"""Generate the Invoice and Invoice Summary PDFs from blueberry.db.

Usage:  pip install reportlab pillow
        python3 build.py && python3 make_pdfs.py
"""
import sqlite3
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import Image, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from build import DB, FORM_INVOICE, ROOT, eur, fi_date

OUT = ROOT / "reports"
LOGO = ROOT / "assets" / "blueberry_logo.png"
FONT_DIR = Path("/usr/share/fonts/truetype/liberation")
NOTE = "Generated by script from the SQLite database blueberry.db. Not a FileMaker export."
BLUE = colors.HexColor("#1F4E9E")
GRID = colors.HexColor("#C9CFD8")
BAND = colors.HexColor("#F2F4F8")

pdfmetrics.registerFont(TTFont("Body", str(FONT_DIR / "LiberationSans-Regular.ttf")))
pdfmetrics.registerFont(TTFont("Bold", str(FONT_DIR / "LiberationSans-Bold.ttf")))

TITLE = ParagraphStyle("title", fontName="Bold", fontSize=18, leading=22, textColor=BLUE)
BODY = ParagraphStyle("body", fontName="Body", fontSize=10, leading=14)
SMALL = ParagraphStyle("small", fontName="Body", fontSize=8, leading=11, textColor=colors.HexColor("#555555"))
RIGHT = ParagraphStyle("right", parent=BODY, fontName="Bold", fontSize=12, alignment=2)


def table_style(right_from):
    return TableStyle([
        ("FONTNAME", (0, 0), (-1, -1), "Body"),
        ("FONTSIZE", (0, 0), (-1, -1), 9.5),
        ("FONTNAME", (0, 0), (-1, 0), "Bold"),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("BACKGROUND", (0, 0), (-1, 0), BLUE),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, BAND]),
        ("LINEBELOW", (0, 0), (-1, -1), 0.4, GRID),
        ("ALIGN", (right_from, 0), (-1, -1), "RIGHT"),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ])


def logo():
    return Image(str(LOGO), width=45 * mm, height=21 * mm, kind="proportional", hAlign="LEFT")


def document(path, title):
    return SimpleDocTemplate(str(path), pagesize=A4, title=title, author="Smyrna V",
                             leftMargin=18 * mm, rightMargin=18 * mm, topMargin=15 * mm, bottomMargin=15 * mm)


def summary_pdf(con):
    rows = con.execute("SELECT * FROM invoice_summary").fetchall()
    grand = sum(r["invoice_total"] for r in rows)
    data = [["Invoice", "Date", "Customer", "Payment day", "Status", "Invoice total"]]
    data += [[r["invoice_number"], fi_date(r["invoice_date"]), r["company_name"], fi_date(r["payment_day"]),
              r["status"], eur(r["invoice_total"])] for r in rows]
    table = Table(data, colWidths=[16 * mm, 24 * mm, 50 * mm, 26 * mm, 18 * mm, 40 * mm], repeatRows=1)
    style = table_style(5)
    style.add("ALIGN", (0, 0), (0, -1), "RIGHT")
    table.setStyle(style)
    story = [logo(), Spacer(1, 3 * mm), Paragraph("Invoice Summary", TITLE), Spacer(1, 4 * mm), table,
             Spacer(1, 4 * mm), Paragraph(f"Grand total: {eur(grand)}", RIGHT),
             Spacer(1, 6 * mm), Paragraph(NOTE, SMALL)]
    path = OUT / "Summary_report_SmyrnaV_SQL.pdf"
    document(path, "Invoice Summary").build(story)
    return path, len(rows), grand


def invoice_pdf(con, number):
    h = con.execute(
        "SELECT v.*, s.payment_day, s.invoice_total, c.* FROM invoices v "
        "JOIN customers c USING (customer_id) JOIN invoice_summary s USING (invoice_number) "
        "WHERE v.invoice_number = ?", (number,)).fetchone()
    facts = Table([["Invoice number", h["invoice_number"]],
                   ["Invoice date", fi_date(h["invoice_date"])],
                   ["Days to payment", h["days_to_payment"]],
                   ["Payment day", fi_date(h["payment_day"])]], colWidths=[34 * mm, 28 * mm])
    facts.setStyle(TableStyle([("FONTNAME", (0, 0), (0, -1), "Body"), ("FONTNAME", (1, 0), (1, -1), "Bold"),
                               ("FONTSIZE", (0, 0), (-1, -1), 10), ("ALIGN", (1, 0), (1, -1), "RIGHT")]))
    header = Table([[logo(), [Paragraph("INVOICE", TITLE), Spacer(1, 2 * mm), facts]]], colWidths=[108 * mm, 66 * mm])
    header.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("LEFTPADDING", (0, 0), (0, 0), 0)]))
    bill_to = (f"Customer ID {h['customer_id']}<br/><b>{h['company_name']}</b><br/>{h['street_address']}<br/>"
               f"{h['postal_code']} {h['city']}<br/>{h['country']}")
    data = [["Item ID", "Item name", "Price", "Amount", "Total"]]
    data += [[r["item_id"], r["item_name"], eur(r["price"]), r["amount"], eur(r["row_total"])]
             for r in con.execute("SELECT * FROM invoice_row_lines WHERE invoice_number = ? ORDER BY row_id", (number,))]
    rows = Table(data, colWidths=[18 * mm, 76 * mm, 28 * mm, 20 * mm, 32 * mm], repeatRows=1)
    rows.setStyle(table_style(2))
    story = [header, Spacer(1, 8 * mm), Paragraph(bill_to, BODY), Spacer(1, 10 * mm), rows, Spacer(1, 5 * mm),
             Paragraph(f"TOTAL {eur(h['invoice_total'])}", RIGHT), Spacer(1, 18 * mm),
             Paragraph("Arcada Accessories, Hameentie 3, 00500 HELSINKI<br/>Bank account 123456-7890<br/>"
                       f"Due date: {fi_date(h['payment_day'])}", BODY),
             Spacer(1, 6 * mm), Paragraph(NOTE, SMALL)]
    path = OUT / "Invoice_SmyrnaV_SQL.pdf"
    document(path, f"Invoice {number}").build(story)
    return path, h["invoice_total"]


def main():
    con = sqlite3.connect(DB)
    con.row_factory = sqlite3.Row
    path, n, grand = summary_pdf(con)
    print(f"{path.name}: {n} invoices, grand total {eur(grand)}")
    path, total = invoice_pdf(con, FORM_INVOICE)
    print(f"{path.name}: invoice {FORM_INVOICE}, total {eur(total)}")
    con.close()


if __name__ == "__main__":
    main()
